        for a1 in p1_alleles:
            for a2 in p2_alleles:
                child = "".join(sorted([a1, a2]))
                if child == "NN": clear_count += 1
                elif child == "Nd": carrier_count += 1
                elif child == "dd": affected_count += 1
                
